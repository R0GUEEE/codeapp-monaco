/**
 * VS Code extension runtime for CodifyOne.
 *
 * The editor bundle is built on @codingame/monaco-vscode-api, which ships the
 * real VS Code extension host plus the full `vscode` API implementation. That
 * host is what makes third-party VSIX packages work: an extension is registered,
 * its manifest contributions (commands, languages, grammars, snippets, themes,
 * configuration) are picked up by the workbench services, and its `activate()`
 * entry point runs inside a sandboxed extension context.
 *
 * Design notes
 * ------------
 *  - Extensions run in the **local extension host** (in-page, same JS context).
 *    That flavour is the only one where `registerFileUrl()` mappings are visible
 *    to the module loader, so it is what lets us serve extension code straight
 *    out of the iOS app's sandbox over the local HTTP server.
 *  - Installed extension bytes live natively in the app
 *    (Application Support/Extensions/<publisher>.<name>). At startup the app
 *    serves that directory at http://127.0.0.1:<port>/ext/ and we read
 *    `/ext/index.json` (generated by `ExtensionRuntime.swift`) to know what to
 *    register. Nothing here writes to the filesystem.
 *  - All of this is opt-in and failure tolerant: if the index is missing the
 *    editor still works exactly as before.
 */

import {
  ExtensionHostKind,
  registerExtension,
} from "vscode/extensions";
import type { IExtensionManifest } from "vscode/extensions";
import * as vscode from "vscode";
import { postToNative } from "./nativeBridge";

export interface ExtensionIndexEntry {
  /** `publisher.name` */
  id: string;
  /** Virtual root used by the extension host, e.g. `/extensions/esbenp.prettier-vscode` */
  path: string;
  /** HTTP base used to fetch the extension files, e.g. `http://127.0.0.1:20234/ext/esbenp.prettier-vscode` */
  baseUrl: string;
  /** Every file in the package, relative to the extension root */
  files: string[];
  /** Raw package.json */
  manifest: IExtensionManifest;
  enabled?: boolean;
  /** Where the package came from, for diagnostics (openvsx / vsix / builtin) */
  source?: string;
}

export interface ExtensionIndex {
  version: number;
  extensions: ExtensionIndexEntry[];
}

/** Shape of the handle returned by `registerExtension(..., LocalProcess)`. */
interface LocalExtensionHandle {
  id: string;
  whenReady(): Promise<void>;
  isEnabled(): Promise<boolean>;
  dispose(): Promise<void>;
  registerFileUrl(path: string, url: string): { dispose(): void };
  getApi(): Promise<typeof vscode>;
}

interface RegisteredExtension {
  entry: ExtensionIndexEntry;
  handle: LocalExtensionHandle;
  api?: typeof vscode;
}

const registered = new Map<string, RegisteredExtension>();
let loading = false;

function log(message: string, ...rest: unknown[]) {
  console.log(`[extensions] ${message}`, ...rest);
}

function commandIdsFromManifest(manifest: IExtensionManifest): string[] {
  const contributions: any = (manifest as any).contributes ?? {};
  return (contributions.commands ?? [])
    .map((command: any) => command?.command)
    .filter((id: unknown): id is string => typeof id === "string");
}

/**
 * Reads the extension index served by the native host.
 * `base` defaults to the directory the editor itself was loaded from.
 */
export async function fetchExtensionIndex(
  base: string = new URL("./", document.baseURI).toString()
): Promise<ExtensionIndex> {
  const url = new URL("ext/index.json", base).toString();
  const response = await fetch(url, { cache: "no-store" });
  if (!response.ok) {
    throw new Error(`extension index unavailable (${response.status})`);
  }
  const index = (await response.json()) as ExtensionIndex;
  if (!index || !Array.isArray(index.extensions)) {
    throw new Error("malformed extension index");
  }
  // Defensive: older hosts may omit fields we rely on.
  index.extensions = index.extensions.filter(
    (entry) => entry && entry.id && entry.manifest && entry.baseUrl
  );
  return index;
}

function absoluteFileUrl(entry: ExtensionIndexEntry, file: string): string {
  const base = entry.baseUrl.endsWith("/") ? entry.baseUrl : `${entry.baseUrl}/`;
  return new URL(file.replace(/^\/+/, ""), base).toString();
}

/**
 * Registers a single extension with the running extension host.
 * Safe to call twice – the second call is a no-op.
 */
export function registerExtensionEntry(
  entry: ExtensionIndexEntry
): LocalExtensionHandle | undefined {
  if (registered.has(entry.id)) return registered.get(entry.id)!.handle;

  const manifest = entry.manifest as IExtensionManifest;
  const isWebExtension = !!(manifest as any).browser;
  const mainFile = (manifest as any).browser ?? (manifest as any).main;

  if (!isWebExtension) {
    // Node-only extensions cannot run in the web extension host. Report it
    // instead of failing silently on activation.
    log(`${entry.id} is not a web extension (no "browser" entry point)`);
    postToNative({
      Event: "Extension Error",
      id: entry.id,
      message:
        "This extension does not ship a web (browser) entry point and cannot run on iOS.",
    });
    return undefined;
  }

  const handle = registerExtension(
    manifest,
    ExtensionHostKind.LocalProcess,
    { path: entry.path }
  );

  for (const file of entry.files) {
    try {
      handle.registerFileUrl(file, absoluteFileUrl(entry, file));
    } catch (e) {
      log(`failed to map ${entry.id}/${file}`, e);
    }
  }

  const record: RegisteredExtension = { entry, handle };
  registered.set(entry.id, record);

  handle
    .whenReady()
    .then(async () => {
      try {
        // `getApi()` also forces the extension to be fully registered with the
        // host, and gives us a way to run contributed commands from native UI.
        record.api = await handle.getApi();
      } catch (e) {
        log(`could not obtain api for ${entry.id}`, e);
      }
      const enabled = await handle.isEnabled();
      const commands = commandIdsFromManifest(manifest);
      log(
        `${entry.id}@${manifest.version} ready (enabled=${enabled}, main=${mainFile})`
      );
      postToNative({
        Event: "Extension Ready",
        id: entry.id,
        version: manifest.version ?? "",
        enabled,
        commands,
      });
    })
    .catch((e: unknown) => {
      const message = e instanceof Error ? e.message : String(e);
      log(`failed to register ${entry.id}`, e);
      postToNative({ Event: "Extension Error", id: entry.id, message });
    });

  return handle;
}

export async function unregisterExtension(id: string): Promise<void> {
  const record = registered.get(id);
  if (!record) return;
  registered.delete(id);
  try {
    await record.handle.dispose();
  } catch (e) {
    log(`failed to dispose ${id}`, e);
  }
  postToNative({ Event: "Extension Unloaded", id });
}

/**
 * Loads and registers every enabled extension from the native index.
 * Returns a small summary; never throws.
 */
export async function loadExtensions(
  base?: string
): Promise<{ loaded: string[]; failed: { id: string; error: string }[] }> {
  const result: { loaded: string[]; failed: { id: string; error: string }[] } =
    { loaded: [], failed: [] };
  if (loading) return result;
  loading = true;
  try {
    const index = await fetchExtensionIndex(base);
    log(`index: ${index.extensions.length} extension(s)`);
    for (const entry of index.extensions) {
      if (entry.enabled === false) continue;
      try {
        const handle = registerExtensionEntry(entry);
        if (handle) result.loaded.push(entry.id);
      } catch (e) {
        const message = e instanceof Error ? e.message : String(e);
        result.failed.push({ id: entry.id, error: message });
        postToNative({ Event: "Extension Error", id: entry.id, message });
      }
    }
  } catch (e) {
    // No index (first run, no extensions installed) is a normal state.
    log(`no extensions loaded: ${e instanceof Error ? e.message : e}`);
  } finally {
    loading = false;
  }
  return result;
}

/**
 * Reconciles the running set with the native index: registers new extensions,
 * unloads ones that were removed or disabled. Called after install/uninstall.
 */
export async function syncExtensions(
  base?: string
): Promise<{ loaded: string[]; failed: { id: string; error: string }[] }> {
  try {
    const index = await fetchExtensionIndex(base);
    const wanted = new Set(
      index.extensions
        .filter((entry) => entry.enabled !== false)
        .map((entry) => entry.id)
    );
    for (const id of [...registered.keys()]) {
      if (!wanted.has(id)) await unregisterExtension(id);
    }
  } catch (e) {
    log(`sync: ${e instanceof Error ? e.message : e}`);
  }
  return loadExtensions(base);
}

/** Runs a command contributed by an extension. */
export async function executeExtensionCommand(
  command: string,
  ...args: unknown[]
): Promise<unknown> {
  const anyRecord = [...registered.values()].find((record) =>
    commandIdsFromManifest(record.entry.manifest).includes(command)
  );
  const api = anyRecord?.api;
  if (!api) {
    throw new Error(`no extension API available to run '${command}'`);
  }
  return api.commands.executeCommand(command, ...args);
}

/** Snapshot of what the host currently knows about, for the native UI. */
export function listRegisteredExtensions() {
  return [...registered.values()].map(({ entry }) => ({
    id: entry.id,
    version: entry.manifest.version,
    enabled: true,
    commands: commandIdsFromManifest(entry.manifest),
  }));
}

/** All command ids contributed by registered extensions. */
export function listExtensionCommands(): { command: string; title: string }[] {
  const commands: { command: string; title: string }[] = [];
  for (const { entry } of registered.values()) {
    const contributes: any = (entry.manifest as any).contributes ?? {};
    for (const command of contributes.commands ?? []) {
      if (command?.command) {
        commands.push({
          command: command.command,
          title: command.title ?? command.command,
        });
      }
    }
  }
  return commands;
}

declare global {
  interface Window {
    codeExtensions: {
      load: typeof loadExtensions;
      sync: typeof syncExtensions;
      register: typeof registerExtensionEntry;
      unregister: typeof unregisterExtension;
      executeCommand: typeof executeExtensionCommand;
      list: typeof listRegisteredExtensions;
      listCommands: typeof listExtensionCommands;
    };
  }
}

export function installExtensionInterface(): void {
  window.codeExtensions = {
    load: loadExtensions,
    sync: syncExtensions,
    register: registerExtensionEntry,
    unregister: unregisterExtension,
    executeCommand: executeExtensionCommand,
    list: listRegisteredExtensions,
    listCommands: listExtensionCommands,
  };
}
